#!/usr/bin/env node
/**
 * Extracts stroke-order paths for the kana and kanji used in the Japanese
 * course from KanjiVG (via the @madcat/kanjivg npm package, a republication
 * of KanjiVG — © Ulrich Apel, CC BY-SA 3.0).
 *
 * Output (committed, so builds do not need the dev dependency):
 *   src/content/ja/strokes.json         — { char: string[] } SVG path data, 109×109 box, in stroke order
 *   src/content/ja/strokes-index.ts     — list of characters with data
 *   src/content/ja/STROKES_LICENSE.md   — attribution and licence notice
 *
 * Usage: npm run strokes
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kvgDir = join(root, 'node_modules/@madcat/kanjivg/dist/main');
if (!existsSync(kvgDir)) {
  console.error('KanjiVG data not found. Run `npm install` first (devDependency @madcat/kanjivg).');
  process.exit(1);
}

const hira = 'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをん';
const kata = 'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロワヲンー';

// Kanji used anywhere in the course content: every .ts source file in
// src/content/ja except the generated index (which would keep stale characters).
const contentFiles = readdirSync(join(root, 'src/content/ja'))
  .filter((f) => f.endsWith('.ts') && f !== 'strokes-index.ts' && !f.endsWith('.test.ts'))
  .sort();
const kanjiSet = new Set();
for (const f of contentFiles) {
  const src = readFileSync(join(root, 'src/content/ja', f), 'utf8');
  for (const ch of src) {
    const c = ch.codePointAt(0);
    if (c >= 0x4e00 && c <= 0x9fff) kanjiSet.add(ch);
  }
}

const chars = [...hira, ...kata, ...[...kanjiSet].sort()];
const out = {};
const missing = [];
for (const ch of chars) {
  const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
  const file = join(kvgDir, `${hex}.svg`);
  if (!existsSync(file)) {
    missing.push(ch);
    continue;
  }
  const svg = readFileSync(file, 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length) out[ch] = paths;
  else missing.push(ch);
}

writeFileSync(join(root, 'src/content/ja/strokes.json'), JSON.stringify(out));
writeFileSync(
  join(root, 'src/content/ja/strokes-index.ts'),
  `// Generated by scripts/build-stroke-data.mjs — do not edit.\n// Characters for which KanjiVG stroke data is bundled (see STROKES_LICENSE.md).\nexport const STROKE_CHARS: string = ${JSON.stringify(Object.keys(out).join(''))};\n`,
);
writeFileSync(
  join(root, 'src/content/ja/STROKES_LICENSE.md'),
  `# Stroke-order data\n\n\`strokes.json\` contains stroke paths for ${Object.keys(out).length} characters extracted from\n**KanjiVG** (https://kanjivg.tagaini.net), copyright © Ulrich Apel and contributors,\nlicensed under **Creative Commons Attribution-Share Alike 3.0**\n(https://creativecommons.org/licenses/by-sa/3.0/).\n\nThe data was obtained from the npm package \`@madcat/kanjivg\` (a republication of KanjiVG)\nand reduced to the SVG path data of each stroke, in stroke order. This derived file is\ndistributed under the same CC BY-SA 3.0 licence. This notice covers only the stroke data;\nsee CONTENT_SOURCES.md for every other resource.\n`,
);
console.log(`Stroke data: ${Object.keys(out).length} characters (${[...kanjiSet].length} kanji). Missing: ${missing.join('') || 'none'}`);
